/** "fgMuted" → "fg-muted". */
export function kebab(key: string): string {
  return key.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
}

/** CSS custom property name for a UI token. */
export function cssVar(key: UiTokenKey): string {
  return `--goi-${kebab(key)}`;
}
